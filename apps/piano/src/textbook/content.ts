export interface Block {
  /** 小見出し */
  h?: string;
  /** 本文（簡易 HTML 可） */
  html?: string;
  /** 図（SVG 文字列） */
  fig?: string;
  /** 図のキャプション */
  cap?: string;
  /** 箇条書き */
  list?: string[];
  /** 表: 1 行目がヘッダ */
  table?: string[][];
  /** ポイントの囲み */
  point?: string;
  /** やってはいけないことの囲み */
  avoid?: string;
}

export interface Chapter {
  id: string;
  num: string;
  title: string;
  /** 取り組む時期の目安 */
  period: string;
  /** この章のゴール（1〜2 文） */
  goal: string;
  blocks: Block[];
  /** できるようになったらチェックする項目 */
  checklist: string[];
}

export interface Part {
  title: string;
  lead: string;
  chapters: Chapter[];
}

const n = (
  letter: "C" | "D" | "E" | "F" | "G" | "A" | "B",
  octave: number,
  extra: Partial<Extract<StaffItem, { kind: "note" }>> = {},
): StaffItem => ({ kind: "note", pitch: pitch(letter, octave), ...extra });

